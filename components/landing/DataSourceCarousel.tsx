// 3D App Card component
function AppCard({
  app,
  index,
  total,
  radius,
  rotation,
}: {
  app: typeof APPS[0];
  index: number;
  total: number;
  radius: number;
  rotation: number;
}) {
  const meshRef = useRef<THREE.Group>(null);
  const angle = (index / total) * Math.PI * 2 + rotation;
  const x = Math.cos(angle) * radius;
  const z = Math.sin(angle) * radius;

  // Calculate if this is the front-facing card
  const normalizedAngle = ((angle % (Math.PI * 2)) + Math.PI * 2) % (Math.PI * 2);
  const isFront = normalizedAngle > Math.PI * 1.75 || normalizedAngle < Math.PI * 0.25;
  const scale = isFront ? 1.2 : 1;
  const opacity = isFront ? 1 : 0.6;

  useFrame(() => {
    if (meshRef.current) {
      // Smooth scale transition
      meshRef.current.scale.lerp(new THREE.Vector3(scale, scale, scale), 0.1);
    }
  });

  return (
    <group ref={meshRef} position={[x, 0, z]} rotation={[0, -angle + Math.PI, 0]}>
      <Float speed={2} rotationIntensity={0} floatIntensity={0.5}>
        {/* Card background */}
        <RoundedBox args={[1.4, 1.4, 0.08]} radius={0.15} smoothness={4}>
          <meshStandardMaterial
            color="#ffffff"
            transparent
            opacity={opacity}
            roughness={0.3}
            metalness={0.1}
          />
        </RoundedBox>

        {/* App icon (colored circle with initial) */}
        <mesh position={[0, 0.05, 0.05]}>
          <circleGeometry args={[0.45, 32]} />
          <meshStandardMaterial color={app.color} />
        </mesh>

        {/* App name label */}
        <Text
          position={[0, -0.55, 0.05]}
          fontSize={0.12}
          color="#333333"
          anchorX="center"
          anchorY="top"
          maxWidth={1.2}
        >
          {app.name}
        </Text>
      </Float>
    </group>
  );
}

// 3D Carousel component
function Carousel3D({ isPaused }: { isPaused: boolean }) {
  const groupRef = useRef<THREE.Group>(null);
  const [rotation, setRotation] = useState(0);
  const radius = 6;

  useFrame((_, delta) => {
    if (!isPaused) {
      setRotation((prev) => prev + delta * 0.15); // Slow rotation
    }
  });

  return (
    <group ref={groupRef} rotation={[0.2, 0, 0]}>
      {APPS.map((app, index) => (
        <AppCard
          key={app.name}
          app={app}
          index={index}
          total={APPS.length}
          radius={radius}
          rotation={rotation}
        />
      ))}
    </group>
  );
}

