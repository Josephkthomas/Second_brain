/**
 * Sleep for specified milliseconds
 */
function sleep(ms: number): Promise<void> {
  return new Promise(resolve => setTimeout(resolve, ms));
}

/**
 * Estimate Apify credits needed for a transcript extraction
 * This is a rough estimate - actual usage depends on video length
 */
export function estimateCreditsNeeded(videoCount: number): number {
  // Rough estimate: 0.05 credits per video (may vary)
  return Math.ceil(videoCount * 0.05 * 100) / 100;
}

/**
 * Clean transcript text for better extraction
 * - Remove timing artifacts
 * - Normalize whitespace
 * - Remove speaker labels if present
 */
export function cleanTranscript(transcript: string): string {
  let cleaned = transcript;

  // Remove common timestamp patterns like [00:00:00] or (00:00)
  cleaned = cleaned.replace(/\[[\d:]+\]/g, '');
  cleaned = cleaned.replace(/\([\d:]+\)/g, '');

  // Remove speaker labels like "Speaker 1:" or "John:"
  cleaned = cleaned.replace(/^[A-Za-z\s]+\d*:\s*/gm, '');

  // Normalize whitespace
  cleaned = cleaned.replace(/\s+/g, ' ');
  cleaned = cleaned.replace(/\n\s*\n/g, '\n\n');

  return cleaned.trim();
}
