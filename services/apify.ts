// APIFY API HELPERS
// ============================================

/**
 * Start an Actor run
 */
async function startActorRun(videoUrl: string, apiKey: string): Promise<ApifyRunResponse> {
  const url = `${APIFY_API_BASE}/acts/${TRANSCRIPT_ACTOR_ID}/runs`;

  const response = await fetch(url, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${apiKey}`,
    },
    body: JSON.stringify({
      startUrls: [{ url: videoUrl }],
    }),
  });

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(`Failed to start Apify run: ${response.status} - ${errorText}`);
  }

  return await response.json();
}

/**
 * Poll for run completion
 */
async function pollRunStatus(runId: string, apiKey: string): Promise<string> {
  const startTime = Date.now();
  let status = 'RUNNING';

  while (status === 'RUNNING' || status === 'READY') {
    // Check timeout
    if (Date.now() - startTime > MAX_WAIT_TIME_MS) {
      throw new Error('Apify run timed out');
    }

    await sleep(POLL_INTERVAL_MS);

    const response = await fetch(`${APIFY_API_BASE}/actor-runs/${runId}`, {
      headers: {
        'Authorization': `Bearer ${apiKey}`,
      },
    });

    if (!response.ok) {
      throw new Error(`Failed to check run status: ${response.status}`);
    }

    const data: ApifyRunResponse = await response.json();
    status = data.data.status;
  }

  return status;
}

/**
 * Fetch results from completed run
 */
async function fetchRunResults(runId: string, apiKey: string): Promise<ApifyTranscriptItem[]> {
  const url = `${APIFY_API_BASE}/actor-runs/${runId}/dataset/items`;

  const response = await fetch(url, {
    headers: {
      'Authorization': `Bearer ${apiKey}`,
    },
  });

  if (!response.ok) {
    throw new Error(`Failed to fetch run results: ${response.status}`);
  }

  return await response.json();
}

