/**
 * Check Apify account info and quota
 * Returns available credits (useful for showing users their remaining quota)
 */
export async function checkApifyAccount(apiKey: string): Promise<{
  valid: boolean;
  username?: string;
  availableCredits?: number;
  error?: string;
}> {
  try {
    const response = await fetch(`${APIFY_API_BASE}/users/me`, {
      headers: {
        'Authorization': `Bearer ${apiKey}`,
      },
    });

    if (!response.ok) {
      if (response.status === 401) {
        return { valid: false, error: 'Invalid API key' };
      }
      return { valid: false, error: `API error: ${response.status}` };
    }

    const data: ApifyAccountInfo = await response.json();

    return {
      valid: true,
      username: data.data.username,
      availableCredits: data.data.availableCredits,
    };
  } catch (error) {
    return {
      valid: false,
      error: error instanceof Error ? error.message : 'Unknown error',
    };
  }
}

/**
 * Validate that an API key is working
 */
export async function validateApifyKey(apiKey: string): Promise<boolean> {
  const result = await checkApifyAccount(apiKey);
  return result.valid;
}

