// Apify Integration Service
// Handles YouTube transcript extraction via Apify Actors

import type { TranscriptResult } from '../types/youtube';

// ============================================
// CONSTANTS
// ============================================

const APIFY_API_BASE = 'https://api.apify.com/v2';
const TRANSCRIPT_ACTOR_ID = 'streamers/youtube-transcript-scraper';

// Timing constants
const MAX_WAIT_TIME_MS = 120000; // 2 minutes max wait
const POLL_INTERVAL_MS = 5000;  // Check every 5 seconds
const DEFAULT_MAX_RETRIES = 3;

// ============================================
// TYPES
// ============================================

interface ApifyRunResponse {
  data: {
    id: string;
    status: string;
    actId: string;
    userId: string;
    startedAt: string;
    finishedAt?: string;
    buildId: string;
    buildNumber: string;
    exitCode?: number;
    defaultKeyValueStoreId: string;
    defaultDatasetId: string;
    defaultRequestQueueId: string;
  };
}

interface ApifyTranscriptItem {
  videoId: string;
  transcript: string;
  language: string;
  isAutoGenerated?: boolean;
}

interface ApifyAccountInfo {
  data: {
    id: string;
    username: string;
    plan: string;
    usedCredits?: number;
    availableCredits?: number;
  };
}

// ============================================
// CORE FUNCTIONS
// ============================================

/**
 * Extract YouTube video transcript using Apify Actor
 *
 * @param videoUrl - Full YouTube video URL (e.g., https://www.youtube.com/watch?v=xxxxx)
 * @param apifyApiKey - User's Apify API key
 * @returns TranscriptResult with transcript text or error
 */
export async function fetchTranscript(
  videoUrl: string,
  apifyApiKey: string
): Promise<TranscriptResult> {
  try {
    // Step 1: Start the Actor run
    const runResponse = await startActorRun(videoUrl, apifyApiKey);
    const runId = runResponse.data.id;

    // Step 2: Poll for completion
    const finalStatus = await pollRunStatus(runId, apifyApiKey);

    if (finalStatus !== 'SUCCEEDED') {
      return {
        success: false,
        transcript: null,
        language: null,
        is_auto_generated: false,
        error: `Apify run failed with status: ${finalStatus}`,
      };
    }

    // Step 3: Fetch the results
    const results = await fetchRunResults(runId, apifyApiKey);

    if (!results || results.length === 0) {
      return {
        success: false,
        transcript: null,
        language: null,
        is_auto_generated: false,
        error: 'No transcript found for this video. It may not have captions available.',
      };
    }

    const transcriptItem = results[0];

    if (!transcriptItem.transcript) {
      return {
        success: false,
        transcript: null,
        language: null,
        is_auto_generated: false,
        error: 'Transcript was empty. The video may not have captions enabled.',
      };
    }

    return {
      success: true,
      transcript: transcriptItem.transcript,
      language: transcriptItem.language || 'en',
      is_auto_generated: transcriptItem.isAutoGenerated ?? true,
    };
  } catch (error) {
    const errorMessage = error instanceof Error ? error.message : 'Unknown error';
    return {
      success: false,
      transcript: null,
      language: null,
      is_auto_generated: false,
      error: `Transcript extraction failed: ${errorMessage}`,
    };
  }
}

/**
 * Extract transcript with retry logic
 * Retries with exponential backoff on transient failures
 */
export async function fetchTranscriptWithRetry(
  videoUrl: string,
  apifyApiKey: string,
  maxRetries: number = DEFAULT_MAX_RETRIES
): Promise<TranscriptResult> {
  let lastResult: TranscriptResult | null = null;

  for (let attempt = 1; attempt <= maxRetries; attempt++) {
    const result = await fetchTranscript(videoUrl, apifyApiKey);

    // Success
    if (result.success) {
      return result;
    }

    lastResult = result;

    // Don't retry if it's a permanent failure (no captions)
    if (result.error?.includes('no captions') ||
        result.error?.includes('not have captions')) {
      return result;
    }

    // Don't retry on the last attempt
    if (attempt < maxRetries) {
      // Exponential backoff: 2s, 4s, 8s
      const backoffMs = Math.pow(2, attempt) * 1000;
      console.log(`Transcript fetch attempt ${attempt} failed, retrying in ${backoffMs}ms...`);
      await sleep(backoffMs);
    }
  }

  return lastResult || {
    success: false,
    transcript: null,
    language: null,
    is_auto_generated: false,
    error: 'Transcript extraction failed after all retries',
  };
}

